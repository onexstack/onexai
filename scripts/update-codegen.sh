# Code generated by scripts/update-codegen.sh. DO NOT EDIT.
#
# Regenerates the Kubernetes codegen artefacts (deepcopy, conversion, defaulter,
# openapi, clientset, informers, listers, applyconfigurations) using the
# k8s.io/code-generator generators (gengo v2, v0.37.0). Mirrors the invocations
# of k8s.io/code-generator/kube_codegen.sh, parameterized for this project.
#
# Usage:
#   make gen-k8s
#   # or directly:
#   bash scripts/update-codegen.sh

set -o errexit
set -o nounset
set -o pipefail

MODULE="github.com/onexstack/onexai"
PROJ_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
BOILERPLATE="${PROJ_ROOT}/scripts/boilerplate/boilerplate.go.txt"

# The generators must match the project's k8s libraries, otherwise the generated
# code can reference APIs that do not exist at the pinned version. Read them
# from go.mod, and fall back to the scaffold defaults when they are absent.
CODEGEN_VERSION="$(cd "${PROJ_ROOT}" && go list -m -f '{{.Version}}' k8s.io/apiserver 2>/dev/null || true)"
CODEGEN_VERSION="${CODEGEN_VERSION:-v0.37.0}"
# openapi-gen lives in kube-openapi (not code-generator) since it moved there.
KUBE_OPENAPI_VERSION="$(cd "${PROJ_ROOT}" && go list -m -f '{{.Version}}' k8s.io/kube-openapi 2>/dev/null || true)"
KUBE_OPENAPI_VERSION="${KUBE_OPENAPI_VERSION:-v0.0.0-20260721132016-d427ff9ee9ad}"

# space-separated list of "group:version" pairs, e.g. "apps:v1beta1 batch:v1beta1".
GROUPS_VERSIONS="agent:v1alpha1 batch:v1beta1 chat:v1alpha1 "

INPUT_PKGS=()   # internal + versioned
VERSIONED_PKGS=()
for gv in ${GROUPS_VERSIONS}; do
  group="${gv%%:*}"
  version="${gv##*:}"
  INPUT_PKGS+=("${MODULE}/pkg/apis/${group}" "${MODULE}/pkg/apis/${group}/${version}")
  VERSIONED_PKGS+=("${MODULE}/pkg/apis/${group}/${version}")
done

# Component-config APIs (internal hub + versioned) follow the same
# generation rules as the served APIs, exactly like kube-controller-manager's
# own config API. They need deepcopy / defaulter / conversion only: nothing
# clients an internal config type.
CONFIG_PKGS=(
  "${MODULE}/pkg/config"
  "${MODULE}/pkg/config/v1beta1"
  "${MODULE}/internal/controller/apis/config"
  "${MODULE}/internal/controller/apis/config/v1beta1"
)

if [[ ${#INPUT_PKGS[@]} -eq 0 ]]; then
  echo "No API groups found; add a group under pkg/apis first." >&2
  exit 0
fi

# Build the generators into the project's build output directory (inside the
# workspace, so that local security policies do not block execution).
GOBIN="${PROJ_ROOT}/_output/codegen-bin"
mkdir -p "${GOBIN}"
export GOBIN
GO111MODULE=on go install \
  "k8s.io/code-generator/cmd/deepcopy-gen@${CODEGEN_VERSION}" \
  "k8s.io/code-generator/cmd/defaulter-gen@${CODEGEN_VERSION}" \
  "k8s.io/code-generator/cmd/conversion-gen@${CODEGEN_VERSION}" \
  "k8s.io/code-generator/cmd/client-gen@${CODEGEN_VERSION}" \
  "k8s.io/code-generator/cmd/informer-gen@${CODEGEN_VERSION}" \
  "k8s.io/code-generator/cmd/lister-gen@${CODEGEN_VERSION}" \
  "k8s.io/code-generator/cmd/applyconfiguration-gen@${CODEGEN_VERSION}"

# openapi-gen lives in a different module, and "go install" refuses to mix
# module versions in one invocation, so it is installed separately.
GO111MODULE=on go install "k8s.io/kube-openapi/cmd/openapi-gen@${KUBE_OPENAPI_VERSION}"

# helpers: deepcopy / defaulter / conversion (internal + versioned).
"${GOBIN}/deepcopy-gen" \
  --output-file zz_generated.deepcopy.go \
  --go-header-file "${BOILERPLATE}" \
  "${INPUT_PKGS[@]}" "${CONFIG_PKGS[@]}"

"${GOBIN}/defaulter-gen" \
  --output-file zz_generated.defaults.go \
  --go-header-file "${BOILERPLATE}" \
  "${INPUT_PKGS[@]}" "${CONFIG_PKGS[@]}"

"${GOBIN}/conversion-gen" \
  --output-file zz_generated.conversion.go \
  --go-header-file "${BOILERPLATE}" \
  "${INPUT_PKGS[@]}" "${CONFIG_PKGS[@]}"

# openapi / client / informer / lister / applyconfiguration (versioned).
client_input=()
for gv in ${GROUPS_VERSIONS}; do
  client_input+=(--input "${gv%%:*}/${gv##*:}")
done

"${GOBIN}/client-gen" \
  --input-base "${PROJ_ROOT}/pkg/apis" \
  "${client_input[@]}" \
  --output-dir "${PROJ_ROOT}/pkg/generated/clientset" \
  --output-pkg "${MODULE}/pkg/generated/clientset" \
  --clientset-name versioned \
  --apply-configuration-package "${MODULE}/pkg/generated/applyconfigurations" \
  --go-header-file "${BOILERPLATE}"

"${GOBIN}/lister-gen" \
  --output-dir "${PROJ_ROOT}/pkg/generated/listers" \
  --output-pkg "${MODULE}/pkg/generated/listers" \
  --go-header-file "${BOILERPLATE}" \
  "${VERSIONED_PKGS[@]}"

"${GOBIN}/informer-gen" \
  --output-dir "${PROJ_ROOT}/pkg/generated/informers" \
  --output-pkg "${MODULE}/pkg/generated/informers" \
  --versioned-clientset-package "${MODULE}/pkg/generated/clientset/versioned" \
  --listers-package "${MODULE}/pkg/generated/listers" \
  --go-header-file "${BOILERPLATE}" \
  "${VERSIONED_PKGS[@]}"

"${GOBIN}/applyconfiguration-gen" \
  --output-dir "${PROJ_ROOT}/pkg/generated/applyconfigurations" \
  --output-pkg "${MODULE}/pkg/generated/applyconfigurations" \
  --go-header-file "${BOILERPLATE}" \
  "${VERSIONED_PKGS[@]}"

# OpenAPI definitions: without these the apiserver refuses to start
# ("cannot find model definition") and 'kubectl explain' has nothing to show.
"${GOBIN}/openapi-gen" \
  --output-dir "${PROJ_ROOT}/pkg/generated/openapi" \
  --output-pkg "${MODULE}/pkg/generated/openapi" \
  --output-file zz_generated.openapi.go \
  --output-model-name-file zz_generated.model_name.go \
  --go-header-file "${BOILERPLATE}" \
  --report-filename /dev/null \
  "${VERSIONED_PKGS[@]}"

echo "Codegen complete."