#!/usr/bin/env bash
#
# controlplane-certs.sh -- generates the certificates and token needed by the
# onexai declarative control plane (oai-declserver), writing an **out-of-repo** values file for helm:
#
#   controlplane-certs.sh [output path]       # defaults to ~/.onexai/controlplane-values.yaml
#   helm upgrade --install onexai manifests/installation/charts/onexai -n onexai-system \
#     -f ~/.onexai/values-secrets.yaml -f ~/.onexai/controlplane-values.yaml ...
#
# The two kinds of certificates have different sources; this is the one place this script must explain:
#
#   1. **The etcd client certificate** must be signed by the CA that the cluster etcd trusts. Production etcd uses
#      the same CA as kube-apiserver (/etc/kubernetes/cert/ca.pem), so this part **can only run on a control
#      plane node**, and ca-key.pem must be readable:
#
#        scp this script to k8s-01, then
#        sudo ETCD_CA_DIR=/etc/kubernetes/cert ./controlplane-certs.sh /tmp/cp-values.yaml
#
#      The script writes ca.pem / client.pem / client-key.pem into the values; **ca-key.pem
#      never leaves that machine** (it is only used to sign this one certificate).
#
#   2. **declserver's own server certificate** is signed by a separate CA (generated on the spot by this script). It
#      deliberately does not reuse the cluster CA: declserver's clients only need to trust the "onexai control
#      plane", and handing the cluster CA to the runtime would let it validate any certificate in the cluster.
#
# Why etcd cannot use anything other than the cluster CA: etcd only does mutual TLS authentication, not authorization; the
# certificate is the only credential. Using the wrong CA does not mean "slightly fewer permissions"; it means it cannot connect.
#
# Idempotent: every run regenerates the certificates and tokens. **Changing the token rolls the runtime** (the checksum
# changes); this is expected; the same goes for changing certificates.
set -euo pipefail

OUT="${1:-$HOME/.onexai/controlplane-values.yaml}"
ETCD_CA_DIR="${ETCD_CA_DIR:-/etc/kubernetes/cert}"

# The declserver Service name and namespace determine the SAN of the server certificate.
SERVICE="${SERVICE:-oai-declserver}"
NAMESPACE="${NAMESPACE:-onexai-system}"
DAYS="${DAYS:-3650}"

need() { command -v "$1" >/dev/null 2>&1 || { echo "缺少 $1" >&2; exit 1; }; }
need openssl

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
umask 077

echo "==> 1/4 控制面服务端 CA 与服务端证书"
openssl req -x509 -newkey rsa:2048 -nodes -days "$DAYS" -sha256 \
  -keyout "$WORK/tls-ca.key" -out "$WORK/tls-ca.crt" \
  -subj "/CN=onexai-controlplane-ca" >/dev/null 2>&1

cat >"$WORK/server.ext" <<EOF
subjectAltName=DNS:${SERVICE},DNS:${SERVICE}.${NAMESPACE},DNS:${SERVICE}.${NAMESPACE}.svc,DNS:${SERVICE}.${NAMESPACE}.svc.cluster.local
extendedKeyUsage=serverAuth
keyUsage=digitalSignature,keyEncipherment
EOF

openssl req -newkey rsa:2048 -nodes -keyout "$WORK/tls.key" -out "$WORK/tls.csr" \
  -subj "/CN=${SERVICE}.${NAMESPACE}.svc" >/dev/null 2>&1
openssl x509 -req -in "$WORK/tls.csr" -CA "$WORK/tls-ca.crt" -CAkey "$WORK/tls-ca.key" \
  -CAcreateserial -out "$WORK/tls.crt" -days "$DAYS" -sha256 \
  -extfile "$WORK/server.ext" >/dev/null 2>&1

echo "==> 2/4 etcd 客户端证书（CN=onexai-declserver）"
if [[ -r "$ETCD_CA_DIR/ca.pem" && -r "$ETCD_CA_DIR/ca-key.pem" ]]; then
  cp "$ETCD_CA_DIR/ca.pem" "$WORK/etcd-ca.pem"
  openssl req -newkey rsa:2048 -nodes -keyout "$WORK/etcd-client.key" \
    -out "$WORK/etcd-client.csr" -subj "/CN=onexai-declserver" >/dev/null 2>&1
  openssl x509 -req -in "$WORK/etcd-client.csr" -CA "$ETCD_CA_DIR/ca.pem" \
    -CAkey "$ETCD_CA_DIR/ca-key.pem" -CAcreateserial \
    -out "$WORK/etcd-client.pem" -days "$DAYS" -sha256 >/dev/null 2>&1
  echo "    已用 $ETCD_CA_DIR/ca.pem 签发"
else
  cat >&2 <<EOF

⚠️  读不到 $ETCD_CA_DIR/ca.pem 与 ca-key.pem，etcd 客户端证书没有生成。

    这一段必须在控制面节点上执行 —— 生产 etcd 只信任 kube-apiserver 的同一套 CA：

      sudo ETCD_CA_DIR=/etc/kubernetes/cert \\
        ./manifests/installation/controlplane-certs.sh /tmp/controlplane-values.yaml

    生成的 values 拷回本机后，与下面这份合并（或者直接在那台机器上跑完再拷回来）。

EOF
  exit 2
fi

echo "==> 3/4 运行时与控制器 token"
RUNTIME_TOKEN="$(openssl rand -hex 32)"
CONTROLLER_TOKEN="$(openssl rand -hex 32)"

echo "==> 4/4 写出 $OUT"
indent() { sed 's/^/        /'; }
{
  cat <<'EOF'
# Generated by manifests/installation/controlplane-certs.sh. **Contains private keys and tokens; do not commit to git.**
controlplane:
  enabled: true
  secrets:
    etcd:
      ca: |
EOF
  indent <"$WORK/etcd-ca.pem"
  printf '      cert: |\n'
  indent <"$WORK/etcd-client.pem"
  printf '      key: |\n'
  indent <"$WORK/etcd-client.key"
  printf '    tls:\n      ca: |\n'
  indent <"$WORK/tls-ca.crt"
  printf '      crt: |\n'
  indent <"$WORK/tls.crt"
  printf '      key: |\n'
  indent <"$WORK/tls.key"
  printf '    runtimeToken: "%s"\n' "$RUNTIME_TOKEN"
  printf '    controllerToken: "%s"\n' "$CONTROLLER_TOKEN"
} >"$OUT"
chmod 600 "$OUT"

echo
echo "完成：${OUT}（600）"
echo "部署： helm upgrade --install onexai manifests/installation/charts/onexai -n ${NAMESPACE} \\"
echo "         -f ~/.onexai/values-secrets.yaml -f ${OUT} --set global.image.tag=<tag>"
