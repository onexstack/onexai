package model

import (
	"time"

	"github.com/onexstack/onexstack/pkg/store/registry"

	"github.com/onexstack/onexai/pkg/dbschema"
)

func init() { registry.Register(&AssetM{}) }

// AssetM is one stored image.
//
// # Why a row and not just a key
//
// A reference can be resolved without a table: the key is in the reference and
// the bytes are in the store. The table is what lets the service answer three
// questions a key cannot.
//
//   - Who uploaded this? Authorisation is keyed by the row's owner, so a client
//     forwarding an asset id it did not upload can be refused. Without the row
//     the only options are to serve anything whose id is guessed, or to sign
//     every URL.
//   - When may this be reclaimed? A row carries the expiry a key has nowhere to
//     put, and the sweep reads it.
//   - Have I seen these bytes before? The digest is what makes a duplicate
//     upload cost nothing.
//
// It is the agent service's table because that service owns the store: it is
// the one holding the media configuration and the only one that writes bytes.
// A second service reaching the table directly would be the arrangement this
// design exists to avoid — it asks the owner over HTTP instead.
type AssetM struct {
	// ID is the identity a reference carries. It is generated by the writer
	// rather than by the database so the object key can be built from it before
	// the insert: the key needs the id, the id would otherwise need the insert,
	// and a row written before its bytes have a key is a row that can point at
	// nothing.
	//
	// It is a string, not the auto-increment integer every other table here
	// uses, and the column says so.
	ID string `gorm:"column:id;primaryKey;size:64" json:"id"`
	// OwnerID is the identity that uploaded the asset — a Lark user id, a
	// platform user id, or a service name. It is what authorisation reads, and
	// it is indexed because the per-user listing and the quota both scan by it.
	OwnerID string `gorm:"column:owner_id;index;size:128;not null;default:''" json:"ownerId"`
	// Kind is the asset kind: image | generated | avatar.
	Kind string `gorm:"column:kind;size:32;not null;default:''" json:"kind"`
	// ObjectKey is where the bytes live, relative to the store root. It is
	// unique because it is the address: two rows naming one key would be one
	// row's bytes served under another row's identity.
	ObjectKey string `gorm:"column:object_key;uniqueIndex;size:512;not null" json:"objectKey"`
	// URL is the object's address, as it was rendered at upload time.
	// It is stored rather than recomputed so that changing the public base URL
	// does not silently rewrite history — old links keep pointing where old
	// clients expect, and a migration is a visible decision rather than a
	// side effect of a config change.
	URL string `gorm:"column:url;size:1024;not null;default:''" json:"url"`
	// MimeType is the sniffed media type, never the type the uploader declared.
	MimeType string `gorm:"column:mime_type;size:128;not null;default:''" json:"mimeType"`
	// Name is the stored object's filename, after sanitisation. It is the
	// uploader's name when that had anything usable in it, and derived from the
	// asset id otherwise.
	Name string `gorm:"column:name;size:255;not null;default:''" json:"name"`
	// Size is the object size in bytes.
	Size int64 `gorm:"column:size;not null;default:0" json:"size"`
	// Width and Height are pixels, or 0 when the format could not be decoded.
	// They are metadata rather than a gate: an image with an unreadable header
	// is still an image whose bytes and type were validated.
	Width  int `gorm:"column:width;not null;default:0" json:"width"`
	Height int `gorm:"column:height;not null;default:0" json:"height"`
	// Sha256 is the hex digest of the bytes. It is what makes a duplicate
	// upload recognisable, and it is indexed so that lookup is a read rather
	// than a scan.
	Sha256 string `gorm:"column:sha256;index;size:64;not null;default:''" json:"sha256"`
	// Source records the producing surface: upload | lark | url | generated.
	Source string `gorm:"column:source;size:32;not null;default:''" json:"source"`
	// ExpiresAt is when the object may be reclaimed. Nil means it does not
	// expire, which is the default: an image the user can still scroll back to
	// must not be collected underneath them. It is a pointer rather than a zero
	// time because "no expiry" and "expired at the epoch" are different
	// answers, and the sweep must not confuse them.
	ExpiresAt *time.Time `gorm:"column:expires_at;index" json:"expiresAt,omitempty"`
	// CreatedAt is set by the database on insert.
	CreatedAt time.Time `gorm:"column:created_at" json:"createdAt"`
}

// TableName returns the physical table name under the configured dialect:
// agent.asset on PostgreSQL, onexai_agent_asset on MySQL.
func (AssetM) TableName() string { return dbschema.Table(dbschema.Agent, "asset") }
